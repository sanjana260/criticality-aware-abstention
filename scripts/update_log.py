#!/usr/bin/env python3
"""Record commits in a shared LaTeX progress log.

Usage:
  python scripts/update_log.py <rev-range>     # e.g. "abc123..HEAD" or "HEAD~3..HEAD"
  python scripts/update_log.py                 # only regenerate report/progress.tex

Each new commit gets one JSON entry in report/entries/ (one file per commit, so
teammates never edit the same lines). report/progress.tex is then regenerated
from all entries, grouped by section. Do not hand-edit progress.tex.

Section comes from a leading tag in the commit subject, e.g. "[reward] add term".
No tag or an unknown tag goes to "Miscellaneous".
"""
import argparse
import json
import pathlib
import re
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
ENTRIES = ROOT / "report" / "entries"
PROGRESS = ROOT / "report" / "progress.tex"

SECTIONS = {
    "data": "Data",
    "reward": "Reward and Training",
    "eval": "Evaluation",
    "judge": "Criticality Judge",
    "docs": "Documentation",
    "checkpoint": "Checkpoints",
    "misc": "Miscellaneous",
}
SECTION_ORDER = list(SECTIONS.values())
TAG_RE = re.compile(r"^\[(\w+)\]\s*")
SKIP_PREFIXES = ("[skip log]",)

LATEX_SPECIAL = {
    "\\": r"\textbackslash{}",
    "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
    "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
}


def esc(text: str) -> str:
    return "".join(LATEX_SPECIAL.get(ch, ch) for ch in text)


def git(*args: str) -> str:
    return subprocess.run(
        ["git", *args], cwd=ROOT, check=True, capture_output=True, text=True
    ).stdout


def commits_in(rev_range: str):
    fmt = "%H%x1f%h%x1f%an%x1f%ad%x1f%s%x1f%b%x1e"
    out = git("log", "--reverse", "--date=short", f"--pretty=format:{fmt}", rev_range)
    for record in out.split("\x1e"):
        record = record.strip("\n")
        if not record:
            continue
        _full, short, author, date, subject, body = record.split("\x1f", 5)
        yield {"short": short, "author": author, "date": date,
               "subject": subject, "body": body.strip()}


def record_commits(rev_range: str) -> None:
    ENTRIES.mkdir(parents=True, exist_ok=True)
    for c in commits_in(rev_range):
        if c["subject"].startswith(SKIP_PREFIXES):
            continue
        if list(ENTRIES.glob(f"*-{c['short']}.json")):
            continue  # already recorded
        match = TAG_RE.match(c["subject"])
        tag = match.group(1).lower() if match else ""
        if tag in SECTIONS:
            section, subject = SECTIONS[tag], c["subject"][match.end():]
        else:
            section, subject = SECTIONS["misc"], c["subject"]
        entry = {"section": section, "author": c["author"], "date": c["date"],
                 "short": c["short"], "subject": subject, "body": c["body"]}
        path = ENTRIES / f"{c['date']}-{c['short']}.json"
        path.write_text(json.dumps(entry, indent=2) + "\n", encoding="utf-8")
        print(f"recorded {path.name}")


def load_entries():
    entries = [json.loads(p.read_text(encoding="utf-8"))
               for p in sorted(ENTRIES.glob("*.json"))]
    return entries


def render(entries) -> str:
    lines = ["% AUTO-GENERATED by scripts/update_log.py. Do not edit by hand.", ""]
    for section in SECTION_ORDER:
        items = [e for e in entries if e["section"] == section]
        if not items:
            continue
        lines.append(rf"\section{{{esc(section)}}}")
        for e in items:
            lines.append(
                rf"\subsection*{{{esc(e['date'])} \quad {esc(e['author'])} "
                rf"\quad \texttt{{{esc(e['short'])}}}}}"
            )
            lines.append(r"\begin{itemize}")
            lines.append(rf"  \item {esc(e['subject'])}")
            if e["body"]:
                lines.append(rf"  \\ \small {esc(e['body'])}")
            lines.append(r"\end{itemize}")
            lines.append("")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("rev_range", nargs="?", help="git revision range to record")
    args = parser.parse_args()
    if args.rev_range:
        record_commits(args.rev_range)
    PROGRESS.write_text(render(load_entries()), encoding="utf-8")
    print(f"wrote {PROGRESS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
